"""Original Paws name labels using the bundled OFL Nunito Sans font."""
from io import BytesIO
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(root / 'assets/runtime/fonts/NunitoSans-Semibold.ttf'), 76)
arrays = ['// Generated by scripts/generate-cat-name-tags.py; original Paws UI artwork.']
for index, name in enumerate(['Pip', 'Mabel', 'Button', 'Pepper']):
    image = Image.new('RGBA', (384, 112))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((3, 3, 380, 108), radius=24, fill='#fff8e9', outline='#28645d', width=5)
    draw.text((192, 53), name, font=font, anchor='mm', fill='#253e37')
    output = BytesIO()
    image.save(output, format='PNG')
    data = output.getvalue()
    arrays.append(f'static constexpr unsigned char catNameTag{index}[]={{')
    arrays.extend(','.join(str(b) for b in data[n:n+24])+',' for n in range(0, len(data), 24))
    arrays.append('};')
(root / 'src/release1/integration/cat_name_tags.inc').write_text('\n'.join(arrays)+'\n', encoding='utf-8')
