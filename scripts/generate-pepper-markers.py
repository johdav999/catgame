"""Original cream/teal interaction labels, embedded like the Paws weight tags.

Uses the repository's OFL Nunito font. No external artwork or runtime files.
"""
from io import BytesIO
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
font_path = ROOT / 'assets/runtime/fonts/NunitoSans-Semibold.ttf'
arrays = ['// Generated by scripts/generate-pepper-markers.py; original Paws UI artwork.']
for index, label in enumerate(['1  PRINTS', '2  THREADS', '3  SCRAPS', 'PATH A', 'PATH B', 'PATH C']):
    for state in range(2):
        image = Image.new('RGBA', (512, 224))
        draw = ImageDraw.Draw(image)
        cream, ink = '#fff8e9', '#253e37'
        background, foreground = ('#28645d', cream) if state else (cream, ink)
        draw.rounded_rectangle((5, 5, 507, 219), radius=30, fill=background, outline=ink, width=7)
        symbol = str(index+1) if index < 3 else 'ABC'[index-3]
        name = ['PRINTS', 'THREADS', 'SCRAPS'][index] if index < 3 else 'PATH'
        draw.text((90, 101), symbol, font=ImageFont.truetype(str(font_path), 146), anchor='mm', fill=foreground)
        draw.text((335, 74), name, font=ImageFont.truetype(str(font_path), 48), anchor='mm', fill=foreground)
        caption = ('EXAMINED' if state else 'TAP TO EXAMINE') if index < 3 else ('TAP TO FOLLOW' if state else 'READ CLUES FIRST')
        caption = caption.replace('TAP TO ', '').replace('READ CLUES FIRST', 'READ CLUES')
        draw.text((335, 154), caption, font=ImageFont.truetype(str(font_path), 29), anchor='mm', fill=foreground)
        if state and index < 3:
            draw.line([(182, 151), (194, 165), (217, 136)], fill=foreground, width=9, joint='curve')
        output = BytesIO()
        image.resize((256, 112), Image.Resampling.LANCZOS).save(output, format='PNG')
        data = output.getvalue()
        arrays.append(f'static constexpr unsigned char pepperTag{index}_{state}[]={{')
        arrays.extend(','.join(str(b) for b in data[n:n+24])+',' for n in range(0, len(data), 24))
        arrays.append('};')
(ROOT / 'src/release1/integration/pepper_tags.inc').write_text('\n'.join(arrays)+'\n', encoding='utf-8')
