"""Compile the delivered manifest's geometry/assembly contract to portable C++.
Run after accepting a new kit revision. --check rejects stale generated bindings.
"""
import json, pathlib, sys
root=pathlib.Path(__file__).resolve().parents[1]
m=json.loads((root/'assets/runtime/models/garden/asset-manifest.json').read_text())
def v(p):return '{'+','.join(f'{x:.8f}f' for x in p)+'}'
lines=['// Generated by scripts/generate-garden-contract.py. Do not edit.','constexpr GardenAsset assetSpecs[]{']
for a in m['assets']:
    name=a['file'][:-4];lines.append(f'{{"{name}","{a["id"]}","assets/models/garden/{a["file"]}",{v(a["bounds"]["min"])},{v(a["bounds"]["max"])},{a["triangles"]}}},')
lines+=['};','constexpr GardenInstance reviewInstances[]{']
for i in m['review_instances']:lines.append(f'{{"{i["asset"]}",{v(i["position"])}}},')
lines+=['};','constexpr GardenAnchor anchorSpecs[]{']
for a in m['assets']:
    for name,p in a['anchors'].items():
        if isinstance(p,list) and len(p)==3:lines.append(f'{{"{a["file"][:-4]}","{name}",{v(p)}}},')
angle=next(a for a in m['assets'] if a['file']=='gate_frame.glb')['anchors']['open_angle_degrees']
lines+=['};',f'constexpr float gateOpenDegrees={angle:.8f}f;',''];text='\n'.join(lines);dest=root/'src/garden_manifest.inc'
if '--check' in sys.argv:
    if dest.read_text()!=text:raise SystemExit('Garden manifest bindings are stale')
else:dest.write_text(text)
