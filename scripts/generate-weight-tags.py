"""Rebuild the original Paws weight-tag UI artwork and embedded PNG resources."""
from pathlib import Path
from io import BytesIO
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/design/weight-tags'
OUT.mkdir(parents=True, exist_ok=True)
S = 3
font = ImageFont.truetype(str(ROOT / 'assets/runtime/fonts/NunitoSans-Semibold.ttf'), 91*S)
arrays = ['// Generated by scripts/generate-weight-tags.py; original Paws UI artwork.']
for number in range(1, 5):
    im = Image.new('RGBA', (128*S, 160*S))
    d = ImageDraw.Draw(im)
    def polygon(points, color):
        d.polygon([(int(x*S), int(y*S)) for x, y in points], fill=color)
    # Rounded garden-label silhouette, inset cream face and restrained edge depth.
    shape = [(15,153),(5,142),(5,48),(9,35),(20,26),(53,7),(64,4),
             (75,7),(108,26),(119,35),(123,48),(123,142),(113,153)]
    polygon(shape, '#245342')
    d.line([(x*S,y*S) for x,y in shape+[shape[0]]], fill='#245342', width=8*S, joint='curve')
    inner = [(18,147),(11,139),(11,48),(15,39),(24,31),(56,13),(64,11),
             (72,13),(104,31),(113,39),(117,48),(117,139),(110,147)]
    polygon(inner, '#fff8e8')
    d.line([(x*S,y*S) for x,y in inner+[inner[0]]], fill='#fff8e8', width=4*S, joint='curve')
    # Familiar balance-weight icon with a clearly open lifting ring.
    d.ellipse((57*S,20*S,71*S,34*S), fill='#245342')
    d.ellipse((61*S,24*S,67*S,30*S), fill='#fff8e8')
    polygon([(55,33),(73,33),(81,53),(47,53)], '#245342')
    d.text((64*S,103*S), str(number), font=font, anchor='mm', fill='#183f32', stroke_width=S)
    im = im.resize((128,160), Image.Resampling.LANCZOS)
    buffer = BytesIO()
    im.save(buffer, format='PNG')
    data = buffer.getvalue()
    (OUT / f'weight-{number}.png').write_bytes(data)
    arrays.append(f'static constexpr unsigned char weightTag{number}[]={{')
    arrays.extend(','.join(str(b) for b in data[i:i+24])+',' for i in range(0,len(data),24))
    arrays.append('};')
(ROOT / 'src/release1/integration/weight_tags.inc').write_text('\n'.join(arrays)+'\n')
