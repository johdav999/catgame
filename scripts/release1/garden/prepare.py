"""Freeze accepted input identities into this task's harness; never stage drafts.

Cats require the producer's accepted fragment AND a measured contact sidecar.
The new mesh can be loaded/inspected before contacts exist; uses remain gated.
"""
from pathlib import Path
import json, hashlib, math
ROOT=Path(__file__).resolve().parents[3]
OUT=ROOT/'src/release1/garden'
def digest(p):return hashlib.sha256(p.read_bytes()).hexdigest()
records=[]
props=json.loads((ROOT/'docs/release1/fragments/props.json').read_text())
for a in props['assets']+props['reuse']:
    p=ROOT/'assets/runtime'/a['url'][7:]
    if 'sha256' in a:
        assert digest(p)==a['sha256'] and p.stat().st_size==a['bytes'],a['id']
catfile=ROOT/'docs/release1/fragments/cats.json'
fragment=json.loads(catfile.read_text()) if catfile.exists() else {'assets':[]}
lines=['// Generated by scripts/release1/garden/prepare.py; accepted inputs only.']
lines+=['static const CatInput catInputs[] = {']
for i,name in enumerate(['pip','mabel','button','pepper']):
    candidates=[a for a in fragment['assets'] if a.get('cat',a.get('name'))==name and a.get('url','').endswith('.glb')]
    a=candidates[0] if candidates else None
    if a:
        p=ROOT/'assets/runtime'/a['url'][7:]
        assert digest(p)==a['sha256'] and p.stat().st_size==a['bytes'],name
        url=a['url'];identity=a['id']
    elif name=='pip':
        p=ROOT/'assets/runtime/models/pip/pip.glb';url='assets/models/pip/pip.glb';identity='cats/pip@1'
    else:
        lines.append('{"'+name+'","",""},');records.append({'cat':name,'status':'missing accepted fragment'});continue
    lines.append('{'+','.join(json.dumps(s) for s in [name,identity,url])+'},')
    records.append({'cat':name,'url':url,'sha256':digest(p),'bytes':p.stat().st_size,'status':'final contact review pending' if a else 'accepted MVP; low rest, nine clips'})
lines.append('};')
(OUT/'inputs.inc').write_text('\n'.join(lines)+'\n')
# A producer/integration reviewer supplies these exact measured records. A false
# verified flag is retained as a visible gate, never auto-upgraded from a filename.
contacts=ROOT/'scripts/release1/garden/contacts.json'
overrides=json.loads(contacts.read_text()) if contacts.exists() else []
lines=['// Generated measured overrides, distinct from unverified prop guides.','void measuredContacts(Assets& assets) {']
for row in overrides:
    i=['pip','mabel','button','pepper'].index(row['cat'])
    identity=records[i]
    assert row['meshSha256']==identity.get('sha256'), 'Contact measurements target a different mesh'
    if not row.get('verified'):continue
    assert row['evidence'] and (ROOT/row['evidence']).exists(),'Missing contact evidence'
    contact=row['contact']
    assert row['item'] in ['garden_cushion','drinking_bowl','scratching_post','sunny_perch','hammock','playhouse','low_picnic_table','picnic_mat']
    def vec(values):
        assert len(values)==3 and all(math.isfinite(float(x)) for x in values)
        return '{'+','.join(str(float(x))+'f' for x in values)+'}'
    assert all(math.isfinite(float(contact[k])) for k in ['yaw','enterSeconds','leaveSeconds','still'])
    path='{'+','.join(vec(v) for v in contact.get('supportedRoots',[]))+'}'
    fields=[vec(contact['approach']),vec(contact['root']),str(float(contact['yaw']))+'f']
    fields += [json.dumps(contact[k]) for k in ['enter','loop','leave']]
    fields += [str(float(contact[k])) for k in ['enterSeconds','leaveSeconds','still']]
    fields += [path,'true']
    lines.append('assets.cats['+str(i)+'].contacts['+json.dumps(row['item'])+']={'+','.join(fields)+'};')
    if row.get('naturalCurl'):lines.append('assets.cats['+str(i)+'].naturalCurl=true;')
lines.append('}')
(OUT/'contacts.inc').write_text('\n'.join(lines)+'\n')
evidence=ROOT/'build/evidence/release1/prompt-06';evidence.mkdir(parents=True,exist_ok=True)
(evidence/'inputs.json').write_text(json.dumps({'cats':records,'propsFragmentSha256':digest(ROOT/'docs/release1/fragments/props.json'),'measuredOverrides':len(overrides)},indent=2)+'\n')
print(json.dumps(records))
