$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot
$folder = Join-Path $root 'docs/design/resource-icons'
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// Generated by scripts/package-resource-icons.ps1 from ImageGen artwork.')
foreach ($name in @('coin','heart')) {
    $source = [System.Drawing.Image]::FromFile((Join-Path $folder "$name-source.png"))
    $bitmap = [System.Drawing.Bitmap]::new(128,128)
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
    try {
        $graphics.Clear([System.Drawing.Color]::Transparent)
        $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $graphics.DrawImage($source,0,0,128,128)
        $path = Join-Path $folder "$name.png"
        $bitmap.Save($path,[System.Drawing.Imaging.ImageFormat]::Png)
        $bytes = [System.IO.File]::ReadAllBytes($path)
        $lines.Add("static constexpr unsigned char ${name}IconPng[] = {")
        for ($offset=0; $offset -lt $bytes.Length; $offset+=24) {
            $end = [Math]::Min($offset+23,$bytes.Length-1)
            $lines.Add(($bytes[$offset..$end] -join ',') + ',')
        }
        $lines.Add('};')
    } finally { $graphics.Dispose(); $bitmap.Dispose(); $source.Dispose() }
}
[System.IO.File]::WriteAllLines((Join-Path $root 'src/resource_icons.inc'),$lines)
